#!/usr/bin/env python3
"""Generate timed ctest bucket files for one big QtTest binary (issue #657).

The full gate runs the window suite as a single 28-minute ctest entry, which
makes it the critical path of every shard. This script splits the binary's
test functions into source-order-contiguous buckets whose summed wall time
stays under --target-seconds, and writes a checked-in CMake file that
CMakeLists.txt includes to register one ctest test per bucket.

Inputs:
  --binary   the built QtTest executable (its -functions output is the truth)
  --timings  a QtTest XML result file from one full solo run:
                 <binary> -o run.xml,xml
  --out      output .cmake file path
Balance is measured, not guessed: every function time is the sum of its
data-row times from --timings; functions missing from the timings count as
0 and are reported so a new case cannot silently unbalance a bucket.
"""
import argparse
import os
import re
import subprocess
import sys
import xml.etree.ElementTree as ET


def functions(binary):
    out = subprocess.run([binary, "-functions"], capture_output=True, text=True)
    if out.returncode != 0:
        sys.exit(f"{binary} -functions failed: {out.stderr.strip()}")
    names = []
    for line in out.stdout.splitlines():
        name = re.sub(r"\(.*\)$", "", line.strip())
        if name in ("initTestCase", "cleanupTestCase"):
            continue
        if name and name not in names:
            names.append(name)
    return names


def timings(path):
    per = {}
    root = ET.parse(path).getroot()
    for case in root.iter("testcase"):
        base = re.sub(r"\(.*\)$", "", case.get("name") or "")
        per[base] = per.get(base, 0.0) + float(case.get("time") or 0.0)
    return per


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--binary", required=True)
    ap.add_argument("--timings", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--target-seconds", type=float, default=20.0)
    ap.add_argument("--prefix", default="WORKSPACE_NATIVE_WINDOW")
    args = ap.parse_args()

    funcs = functions(args.binary)
    per = timings(args.timings)
    unknown = [f for f in funcs if f not in per]
    if unknown:
        print(f"WARNING: {len(unknown)} functions missing from timings: "
              + ", ".join(unknown), file=sys.stderr)

    buckets, current, budget = [], [], 0.0
    for f in funcs:
        cost = per.get(f, 0.0)
        if current and budget + cost > args.target_seconds:
            buckets.append(current)
            current, budget = [], 0.0
        current.append(f)
        budget += cost
    if current:
        buckets.append(current)

    total = sum(per.get(f, 0.0) for f in funcs)
    with open(args.out, "w") as out:
        out.write("# Generated by scripts/gen-test-buckets.py - do not edit.\n")
        out.write(f"# source: {os.path.basename(args.binary)} timings total "
                  f"{total:.1f}s, target {args.target_seconds:g}s per bucket\n")
        out.write(f"set({args.prefix}_BUCKETS_COUNT {len(buckets)})\n")
        for i, bucket in enumerate(buckets, 1):
            out.write(f"set({args.prefix}_BUCKET_{i} " + ";".join(bucket) + ")\n")
    print(f"{len(funcs)} functions -> {len(buckets)} buckets "
          f"(max bucket {max(sum(per.get(f, 0.0) for f in b) for b in buckets):.1f}s) "
          f"written to {args.out}")


if __name__ == "__main__":
    main()
